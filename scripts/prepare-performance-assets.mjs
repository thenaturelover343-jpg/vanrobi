#!/usr/bin/env node
import { createRequire } from "node:module";
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const publicDir = join(root, "public");
const sourceDirs = [
  "assets/cats",
  "assets/products-catalog",
  "assets/products-official",
  "assets/products-stage",
  "worlds",
  "products",
];
const fontFiles = [
  {
    file: "ibm-plex-sans-latin.woff2",
    url: "https://fonts.gstatic.com/s/ibmplexsans/v23/zYXzKVElMYYaJe8bpLHnCwDKr932-G7dytD-Dmu1syxeKYY.woff2",
  },
  {
    file: "instrument-serif-latin.woff2",
    url: "https://fonts.gstatic.com/s/instrumentserif/v5/jizBRFtNs2ka5fXjeivQ4LroWlx-6zUTjg.woff2",
  },
  {
    file: "instrument-serif-latin-italic.woff2",
    url: "https://fonts.gstatic.com/s/instrumentserif/v5/jizHRFtNs2ka5fXjeivQ4LroWlx-6zAjjH7M.woff2",
  },
];
const require = createRequire(import.meta.url);
const runtimeModules = process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES;
if (!runtimeModules) throw new Error("Missing CODEX_PRIMARY_RUNTIME_NODE_MODULES");
const sharp = require(join(runtimeModules, "sharp"));

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) return filesIn(path);
      return /\.(jpe?g|png)$/i.test(entry.name) ? [path] : [];
    }),
  );
  return nested.flat();
}

async function writeFonts() {
  const folder = join(publicDir, "fonts");
  await mkdir(folder, { recursive: true });
  await Promise.all(
    fontFiles.map(async ({ file, url }) => {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`Unable to download ${file}: ${response.status}`);
      await writeFile(join(folder, file), Buffer.from(await response.arrayBuffer()));
    }),
  );
}

async function optimizeImage(file) {
  const rel = `/${relative(publicDir, file).split(sep).join("/")}`;
  const base = file.replace(/\.(jpe?g|png)$/i, "");
  const image = sharp(file).rotate();
  const metadata = await image.metadata();
  await Promise.all([
    image.clone().webp({ quality: 74, effort: 4, smartSubsample: true }).toFile(`${base}.webp`),
    image.clone().avif({ quality: 50, effort: 4 }).toFile(`${base}.avif`),
  ]);
  return [rel, { width: metadata.width ?? 1600, height: metadata.height ?? 900 }];
}

async function main() {
  const sourceFiles = (
    await Promise.all(sourceDirs.map((directory) => filesIn(join(publicDir, directory))))
  ).flat();
  const dimensions = Object.fromEntries(await Promise.all(sourceFiles.map(optimizeImage)));
  const generated = `/** Generated by scripts/prepare-performance-assets.mjs. */\nexport const imageDimensions: Record<string, { width: number; height: number }> = ${JSON.stringify(dimensions, null, 2)};\n`;
  await writeFile(join(root, "src/lib/image-dimensions.generated.ts"), generated);
  await writeFonts();
  const total = await Promise.all(sourceFiles.map((file) => stat(file)));
  console.log(
    `Optimized ${sourceFiles.length} images from ${total.reduce((sum, item) => sum + item.size, 0)} bytes`,
  );
}

await main();
